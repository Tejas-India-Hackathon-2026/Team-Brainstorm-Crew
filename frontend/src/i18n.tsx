const I18nContext = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: string) => string }>({
  lang: "en",
  setLang: () => {},
  t: (k) => k,
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    storage.getItem("ss_lang", "en").then((l) => setLangState((l as Lang) || "en"));
  }, []);
  const setLang = (l: Lang) => {
    setLangState(l);
    storage.setItem("ss_lang", l);
  };
  const t = (k: string) => dict[k]?.[lang] ?? dict[k]?.en ?? k;
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
